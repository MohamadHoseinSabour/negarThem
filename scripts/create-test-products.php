	$product_attributes = array();
	$pos = 0;
	foreach ( $data['specs'] as $spec_label => $spec_value ) {
		$attr_key = sanitize_title( $spec_label );
		if ( empty( $attr_key ) ) {
			$attr_key = 'attr_' . $pos;
		}
		$product_attributes[ $attr_key ] = array(
			'name'         => $spec_label,
			'value'        => $spec_value,
			'position'     => $pos++,
			'is_visible'   => 1,
			'is_variation' => 0,
			'is_taxonomy'  => 0,
		);
	}

	// Update meta
	update_post_meta( $product_id, '_sku', $data['sku'] );
	update_post_meta( $product_id, '_regular_price', $data['regular_price'] );
	update_post_meta( $product_id, '_sale_price', $data['sale_price'] );
	update_post_meta( $product_id, '_price', $data['sale_price'] ? $data['sale_price'] : $data['regular_price'] );
	update_post_meta( $product_id, '_manage_stock', 'no' );
	update_post_meta( $product_id, '_stock_status', 'instock' );
	update_post_meta( $product_id, 'total_sales', '0' );
	update_post_meta( $product_id, '_virtual', 'no' );
	update_post_meta( $product_id, '_downloadable', 'no' );
	update_post_meta( $product_id, '_tax_status', 'taxable' );
	update_post_meta( $product_id, '_product_attributes', $product_attributes );

	// Attach featured image
	$img_id = negar_register_product_image( $data['image_slug'], $data['title'] );
	if ( $img_id ) {
		set_post_thumbnail( $product_id, $img_id );
	}

	// Sync WooCommerce product lookup table
	wc_delete_product_transients( $product_id );
	wc_update_product_lookup_tables( $product_id );

	echo "[$action] ID: {$product_id} | Cat: {$data['category']} | Title: {$data['title']}\n";
}

// Recount terms for product_cat
wp_defer_term_counting( false );
delete_transient( 'wc_count_comments' );
delete_transient( 'wc_term_counts' );
wc_recount_after_stock_change( 0 );

echo "\nSummary: {$created_count} created, {$updated_count} updated. All 35 products processed successfully!\n";
