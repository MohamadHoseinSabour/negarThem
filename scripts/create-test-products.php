// Helper function to register an image as an attachment in WordPress
function negar_register_product_image( $slug, $title ) {
	$file_path = "X:/apps/wamp/www/wp4/wp-content/uploads/appliances/products/{$slug}.png";
	if ( ! file_exists( $file_path ) ) {
		return 0;
	}

	$file_name = basename( $file_path );
	$wp_upload_dir = wp_upload_dir();
	$target_path = $wp_upload_dir['path'] . '/' . $file_name;

	// Copy to current uploads directory if not already there
	if ( ! file_exists( $target_path ) ) {
		copy( $file_path, $target_path );
	}

	$target_url = $wp_upload_dir['url'] . '/' . $file_name;

	// Check if already registered
	$existing = get_posts( array(
		'post_type'   => 'attachment',
		'meta_key'    => '_wp_attached_file',
		'meta_value'  => $wp_upload_dir['subdir'] . '/' . $file_name,
		'post_status' => 'inherit',
		'numberposts' => 1,
	) );

	if ( ! empty( $existing ) ) {
		return $existing[0]->ID;
	}

	$attachment = array(
		'guid'           => $target_url,
		'post_mime_type' => 'image/png',
		'post_title'     => $title,
		'post_content'   => '',
		'post_status'    => 'inherit',
	);

	$attach_id = wp_insert_attachment( $attachment, $target_path );
	if ( ! is_wp_error( $attach_id ) ) {
		require_once ABSPATH . 'wp-admin/includes/image.php';
		$attach_data = wp_generate_attachment_metadata( $attach_id, $target_path );
		wp_update_attachment_metadata( $attach_id, $attach_data );
		return $attach_id;
	}

	return 0;
}

